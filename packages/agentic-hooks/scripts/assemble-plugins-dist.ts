/**
 * Assemble the tree published to the `plugins-dist` branch, from a checkout
 * where `bundle-hooks` has already built every payload's `dist/`.
 *
 * Usage: pnpm exec tsx packages/agentic-hooks/scripts/assemble-plugins-dist.ts <out-dir>
 *
 * The branch is what the public marketplace installs from: the root
 * `.claude-plugin/marketplace.json` on main points each plugin at
 * `plugins/<name>` on `plugins-dist` via a `git-subdir` source. Main never
 * commits a bundle; this branch is the only place one is committed.
 *
 * Two transforms, both load-bearing:
 *
 * - `version` is removed from every manifest. With no manifest or entry
 *   version, Claude Code versions a git-subdir plugin by the source commit SHA
 *   (plus a hash of the subdirectory), so each publish is an update. A fixed
 *   `version` would keep every installed copy on its cache until a human
 *   remembered to bump it.
 * - The branch carries its own `.claude-plugin/marketplace.json` with relative
 *   sources, so `/plugin marketplace add OpenThrottle/monorepo#plugins-dist`
 *   also works without going back through main.
 *
 * Refuses to run when a payload has no `dist/`: publishing stubs with nothing
 * behind them would ship hooks that silently do nothing.
 */
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const workspaceRoot = path.resolve(scriptDir, '..', '..', '..');

const MANIFESTS = ['plugin.json', '.claude-plugin/plugin.json'];

const readJsonObject = (file: string): Record<string, unknown> => {
  const parsed: unknown = JSON.parse(readFileSync(file, 'utf8'));
  if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) {
    throw new Error(`${file} is not a JSON object`);
  }
  return Object.fromEntries(Object.entries(parsed));
};

const writeJson = (file: string, value: unknown): void => {
  writeFileSync(file, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
};

const payloadNames = (): readonly string[] => {
  const pluginsDir = path.join(workspaceRoot, 'plugins');
  return readdirSync(pluginsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith('.'))
    .map((entry) => entry.name)
    .sort();
};

const assemble = (outDir: string): void => {
  const names = payloadNames();
  const unbuilt = names.filter(
    (name) => !existsSync(path.join(workspaceRoot, 'plugins', name, 'dist')),
  );
  if (unbuilt.length > 0) {
    throw new Error(
      `unbuilt payload(s): ${unbuilt.join(', ')}. Run: pnpm run build:hooks`,
    );
  }

  const outPlugins = path.join(outDir, 'plugins');
  mkdirSync(outPlugins, { recursive: true });
  for (const name of names) {
    const target = path.join(outPlugins, name);
    cpSync(path.join(workspaceRoot, 'plugins', name), target, {
      recursive: true,
    });
    for (const manifest of MANIFESTS) {
      const file = path.join(target, manifest);
      if (existsSync(file)) {
        const { version: _version, ...rest } = readJsonObject(file);
        writeJson(file, rest);
      }
    }
  }

  const marketplace = readJsonObject(
    path.join(workspaceRoot, '.claude-plugin', 'marketplace.json'),
  );
  const plugins = Array.isArray(marketplace.plugins) ? marketplace.plugins : [];
  mkdirSync(path.join(outDir, '.claude-plugin'), { recursive: true });
  writeJson(path.join(outDir, '.claude-plugin', 'marketplace.json'), {
    ...marketplace,
    plugins: plugins.map((entry: unknown) => {
      if (typeof entry !== 'object' || entry === null) {
        return entry;
      }
      const name = Reflect.get(entry, 'name');
      return {
        ...Object.fromEntries(Object.entries(entry)),
        source: `./plugins/${String(name)}`,
      };
    }),
  });

  writeFileSync(
    path.join(outDir, 'README.md'),
    [
      '# plugins-dist',
      '',
      'GENERATED by `.github/workflows/publish-plugins.yml` from `main` — do not edit or push',
      'here by hand. This branch holds the built OpenThrottle hook plugins that the public',
      'marketplace installs; the sources live in `packages/agentic-hooks/` on `main`.',
      '',
      '```bash',
      '/plugin marketplace add OpenThrottle/monorepo',
      '/plugin install openthrottle@openthrottle',
      '```',
      '',
    ].join('\n'),
    'utf8',
  );
};

const outArg = process.argv[2];
if (outArg === undefined || outArg === '') {
  process.stderr.write('usage: assemble-plugins-dist.ts <out-dir>\n');
  process.exit(2);
}
assemble(path.resolve(outArg));
process.stdout.write(`assembled plugins-dist into ${outArg}\n`);
