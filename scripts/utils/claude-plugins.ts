/**
 * @description This repository consumes its own Claude Code plugins
 * (`openthrottle`, `openthrottle-workflow`, `openthrottle-guards`) the way any
 * other repository does, instead of registering hooks in
 * `.claude/settings.json`. Committed `enabledPlugins` names them, but enabling
 * installs nothing, so setup and worktree provisioning do the one-time
 * per-machine and per-checkout steps here. Design:
 * `docs/monorepo/hook-plugin-distribution.md` §5.
 *
 * Two facts, probed against Claude Code 2.1.322, shape this:
 *
 * - A marketplace NAME is global per machine. Adding one again silently
 *   repoints every repository's installs at the new source. So this adds
 *   `openthrottle-dev` only when it is absent, pointing at the PRIMARY
 *   checkout (which outlives its worktrees), and never repoints one that
 *   already exists from elsewhere: it reports the command instead.
 * - Installs are recorded per project path. `--scope local` records this
 *   checkout and writes the gitignored `.claude/settings.local.json`, where
 *   `--scope project` would rewrite the committed settings file.
 *
 * A directory marketplace loads its plugins in place, so a rebuilt bundle
 * applies at the next session without `/plugin update`.
 *
 * Owner-approved (OT plan 88d08c18). `OPENTHROTTLE_CLAUDE_PLUGINS=0` opts out.
 * Dependency-free (node builtins + ./exec.ts + ./git.ts): provisioning runs
 * under bare Node before `pnpm install`.
 */
import { run } from './exec.ts';
import { primaryCheckoutDir } from './git.ts';

/**
 * The checkout's own marketplace, from `plugins/.claude-plugin/marketplace.json`
 * (generated by bundle-hooks, relative sources). Distinct from the public
 * `openthrottle` marketplace so the two never collide; committed settings
 * disable the public ids in this repo, so neither double-fires.
 */
export const CLAUDE_MARKETPLACE_NAME = 'openthrottle-dev';

/** Where the dev marketplace lives, relative to a checkout. */
export const CLAUDE_MARKETPLACE_DIR = 'plugins';

/** The plugins this repository enables, telemetry first (the others depend on it). */
export const REPO_CLAUDE_PLUGINS: readonly string[] = [
  'openthrottle',
  'openthrottle-workflow',
  'openthrottle-guards',
];

/** The env switch that turns every step here off. */
export const CLAUDE_PLUGINS_OPT_OUT_ENV = 'OPENTHROTTLE_CLAUDE_PLUGINS';

/** One `claude` invocation's outcome, as the steps need it. */
export interface ClaudeRunResult {
  readonly exitCode: number;
  readonly stderr: string;
  readonly stdout: string;
}

/** Runs `claude <args>` in `cwd`; injected for tests. */
export type ClaudeRunner = (
  args: readonly string[],
  cwd: string,
) => ClaudeRunResult;

/** Outcome of {@link ensureRepoClaudePlugins}. */
export type EnsureClaudePluginsResult =
  | {
      readonly installed: readonly string[];
      readonly kind: 'ok';
      readonly marketplace: 'added' | 'present';
    }
  | { readonly kind: 'conflict'; readonly source: string }
  | { readonly kind: 'failed'; readonly message: string }
  | { readonly kind: 'skipped'; readonly reason: string };

export interface EnsureClaudePluginsOptions {
  /** The checkout to install for (a worktree, or the primary itself). */
  readonly checkout: string;
  /** Environment to read the opt-out from. */
  readonly env: NodeJS.ProcessEnv;
  /** Whether a `claude` binary is on PATH; injected for tests. */
  readonly isClaudeInstalled: () => boolean;
  /** The primary checkout the marketplace should point at. */
  readonly primary: string;
  readonly runClaude: ClaudeRunner;
}

/** True when a `claude` binary resolves on PATH. */
export const claudeOnPath = (): boolean => {
  return run('claude', ['--version'], { allowFailure: true }).exitCode === 0;
};

const runClaudeCli: ClaudeRunner = (args, cwd) => {
  const result = run('claude', [...args], { allowFailure: true, cwd });
  return {
    exitCode: result.exitCode,
    stderr: result.stderr,
    stdout: result.stdout,
  };
};

/** The registered source of the `openthrottle` marketplace, or null when it is absent. */
const findMarketplaceSource = (
  stdout: string,
): { readonly path: string | null; readonly source: string } | null => {
  const parsed: unknown = JSON.parse(stdout);
  if (!Array.isArray(parsed)) {
    return null;
  }
  for (const entry of parsed) {
    if (
      typeof entry === 'object' &&
      entry !== null &&
      Reflect.get(entry, 'name') === CLAUDE_MARKETPLACE_NAME
    ) {
      const source = Reflect.get(entry, 'source');
      const dir = Reflect.get(entry, 'path');
      const repo = Reflect.get(entry, 'repo');
      const kind = typeof source === 'string' ? source : 'unknown';
      return {
        path: typeof dir === 'string' ? dir : null,
        source: typeof repo === 'string' ? `${kind}:${repo}` : kind,
      };
    }
  }
  return null;
};

/**
 * Idempotently make this checkout load the repo's own plugins. Never throws:
 * a failure is returned, so setup and provisioning can log it and carry on —
 * the hooks are a convenience, not a precondition of a working checkout.
 */
export const ensureRepoClaudePlugins = (
  options: EnsureClaudePluginsOptions,
): EnsureClaudePluginsResult => {
  const { checkout, env, isClaudeInstalled, primary, runClaude } = options;

  if (env[CLAUDE_PLUGINS_OPT_OUT_ENV] === '0') {
    return { kind: 'skipped', reason: `${CLAUDE_PLUGINS_OPT_OUT_ENV}=0` };
  }
  if (!isClaudeInstalled()) {
    return { kind: 'skipped', reason: 'claude is not installed' };
  }

  const marketplaceDir = `${primary}/${CLAUDE_MARKETPLACE_DIR}`;

  try {
    const listed = runClaude(['plugin', 'marketplace', 'list', '--json'], checkout); // prettier-ignore
    if (listed.exitCode !== 0) {
      return { kind: 'failed', message: listed.stderr || 'claude plugin marketplace list failed' }; // prettier-ignore
    }

    const existing = findMarketplaceSource(listed.stdout);
    let marketplace: 'added' | 'present' = 'present';
    if (existing === null) {
      const added = runClaude(['plugin', 'marketplace', 'add', marketplaceDir], checkout); // prettier-ignore
      if (added.exitCode !== 0) {
        return { kind: 'failed', message: added.stderr || 'claude plugin marketplace add failed' }; // prettier-ignore
      }
      marketplace = 'added';
    } else if (
      existing.source !== 'directory' ||
      existing.path !== marketplaceDir
    ) {
      return { kind: 'conflict', source: existing.path ?? existing.source };
    }

    const installed = REPO_CLAUDE_PLUGINS.filter((plugin) => {
      const result = runClaude(['plugin', 'install', `${plugin}@${CLAUDE_MARKETPLACE_NAME}`, '--scope', 'local'], checkout); // prettier-ignore
      return result.exitCode === 0;
    });

    if (installed.length !== REPO_CLAUDE_PLUGINS.length) {
      const missing = REPO_CLAUDE_PLUGINS.filter((plugin) => !installed.includes(plugin)); // prettier-ignore
      return { kind: 'failed', message: `could not install ${missing.join(', ')}` }; // prettier-ignore
    }

    return { installed, kind: 'ok', marketplace };
  } catch (error) {
    return { kind: 'failed', message: error instanceof Error ? error.message : String(error) }; // prettier-ignore
  }
};

/** A log line for a result worth telling the operator about; undefined when there is nothing new. */
export const describeClaudePluginsResult = (
  result: EnsureClaudePluginsResult,
  primary: string,
):
  { readonly level: 'info' | 'warn'; readonly message: string } | undefined => {
  switch (result.kind) {
    case 'ok': {
      const added = result.marketplace === 'added' ? `added the ${CLAUDE_MARKETPLACE_NAME} marketplace from ${primary}/${CLAUDE_MARKETPLACE_DIR}; ` : ''; // prettier-ignore
      return { level: 'info', message: `🔌 claude: ${added}enabled ${result.installed.join(', ')} for this checkout (${CLAUDE_PLUGINS_OPT_OUT_ENV}=0 opts out)` }; // prettier-ignore
    }
    case 'conflict': {
      return { level: 'warn', message: `claude: the ${CLAUDE_MARKETPLACE_NAME} marketplace already points at ${result.source}, so this checkout's hooks come from there. To use this checkout's: claude plugin marketplace add ${primary}/${CLAUDE_MARKETPLACE_DIR}` }; // prettier-ignore
    }
    case 'failed': {
      return { level: 'warn', message: `claude: could not enable the repo plugins: ${result.message}` }; // prettier-ignore
    }
    case 'skipped': {
      return undefined;
    }
  }
};

/**
 * Setup/provision entry: enable the repo plugins for the checkout at `cwd`,
 * against the primary checkout that owns it, and return the line worth logging.
 */
export const ensureCheckoutClaudePlugins = (
  cwd: string,
  env: NodeJS.ProcessEnv,
): ReturnType<typeof describeClaudePluginsResult> => {
  const primary = primaryCheckoutDir(cwd);

  if (primary === undefined) {
    return undefined;
  }

  return describeClaudePluginsResult(
    ensureRepoClaudePlugins({ checkout: cwd, env, isClaudeInstalled: claudeOnPath, primary, runClaude: runClaudeCli }), // prettier-ignore
    primary,
  );
};
