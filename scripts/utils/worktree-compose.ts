/**
 * @description The generated `docker-compose.worktree.yml` override. One source
 * for the provisioner (which writes it) and `worktree:db isolate` (which
 * rewrites it): a `shared` worktree skips the postgres/redis services (its apps
 * talk to the primary's database on the host); an `isolated` one stops
 * excluding them, so `database:start` starts the worktree's OWN containers
 * under its own compose project.
 *
 * Dependency-free — it runs during provisioning, before `pnpm install`.
 */

/** Name of the generated, git-ignored override file at the worktree root. */
export const WORKTREE_COMPOSE_FILE = 'docker-compose.worktree.yml';

/** Postgres/Redis ownership a generated override encodes. */
export type WorktreeComposeDb = 'isolated' | 'shared';

const SHARED_DB_SERVICES = `  postgres:
    profiles: ["disabled"]
  redis:
    profiles: ["disabled"]
`;

const SHARED_HEADER = `# Worktrees share the main checkout's Postgres/Redis. This override disables the
# postgres/redis services and points the apps at the host DB. Bring up the apps
# with both files:`;

const ISOLATED_HEADER = `# This worktree owns its Postgres/Redis (OT_WORKTREE_DB=isolated, set by
# \`pnpm worktree:db isolate\`): the postgres/redis services are NOT disabled, and
# the apps reach them on the host ports in this worktree's .env. Bring up the
# apps with both files:`;

/** The override file contents for a worktree that shares, or owns, its database. */
export const worktreeComposeOverride = (db: WorktreeComposeDb): string =>
  `# Generated by scripts/setup_worktree.ts — DO NOT edit by hand.
#
${db === 'shared' ? SHARED_HEADER : ISOLATED_HEADER}
#   docker compose -f docker-compose.yml -f docker-compose.worktree.yml up
#   docker compose -f docker-compose.yml -f docker-compose.worktree.yml --profile dev up
services:
${db === 'shared' ? SHARED_DB_SERVICES : ''}  server:
    depends_on: !reset null
    environment:
      POSTGRES_HOST: host.docker.internal
      REDIS_HOST: host.docker.internal
  server-dev:
    depends_on: !reset null
    environment:
      POSTGRES_HOST: host.docker.internal
      POSTGRES_PORT: \${POSTGRES_PORT}
      REDIS_HOST: host.docker.internal
      REDIS_PORT: \${REDIS_PORT}
`;
