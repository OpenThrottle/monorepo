import { mkdirSync, mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import type { QueryResultRow } from 'pg';
import { describe, expect, it } from 'vitest';

import type { JsonObject } from '../generate-cms-schemas.ts';
import { schemaVersion } from '../generate-cms-schemas.ts';
import type { CmsSchemaSyncClient } from '../openthrottle-database-sync-cms-schemas.ts';
import {
  CmsSchemaSyncError,
  describeCmsSchemaSync,
  findCmsSchemaManifests,
  readCmsSchemaEntries,
  readCmsSchemaManifest,
  syncCmsSchemas,
} from '../openthrottle-database-sync-cms-schemas.ts';

const HERO: JsonObject = { properties: { copy: { type: 'string' } }, title: 'Hero', type: 'object' }; // prettier-ignore

interface FakePackage {
  readonly name: string;
  readonly schemas: readonly (readonly [
    string,
    JsonObject,
    string | undefined,
  ])[];
}

/** A throwaway repo root with `packages/<name>/schemas/` per package. */
const makeRoot = (packages: readonly FakePackage[]): string => {
  const root = mkdtempSync(join(tmpdir(), 'cms-schema-sync-'));
  mkdirSync(join(root, 'packages', 'no-schemas'), { recursive: true });

  for (const pkg of packages) {
    const dir = join(root, 'packages', pkg.name, 'schemas');
    mkdirSync(dir, { recursive: true });
    const entries = pkg.schemas.map(([typename, schema, version]) => {
      writeFileSync(join(dir, `${typename}.schema.json`), JSON.stringify({ $comment: 'GENERATED', ...schema })); // prettier-ignore

      return { file: `${typename}.schema.json`, typename, version: version ?? schemaVersion(schema) }; // prettier-ignore
    });
    writeFileSync(join(dir, 'manifest.json'), JSON.stringify({ schemas: entries })); // prettier-ignore
  }

  return root;
};

interface RecordedQuery {
  readonly text: string;
  readonly values: unknown[] | undefined;
}

/** A client that records every statement and answers from `rowsFor`. */
const makeClient = (
  rowsFor: (text: string) => QueryResultRow[] | Error,
): { client: CmsSchemaSyncClient; queries: RecordedQuery[] } => {
  const queries: RecordedQuery[] = [];
  const client: CmsSchemaSyncClient = {
    query: async <TRow extends QueryResultRow>(
      text: string,
      values?: unknown[],
    ) => {
      queries.push({ text, values });
      const rows = rowsFor(text);

      if (rows instanceof Error) {
        throw rows;
      }

      return { rows: rows.filter((row): row is TRow => { return row !== null; }) }; // prettier-ignore
    },
  };

  return { client, queries };
};

describe('findCmsSchemaManifests', () => {
  it('lists only packages that have schemas/manifest.json, sorted', () => {
    const root = makeRoot([
      { name: 'ui', schemas: [['Hero', HERO, undefined]] },
      { name: 'core', schemas: [] },
    ]);

    expect(findCmsSchemaManifests(root)).toEqual([
      join(root, 'packages', 'core', 'schemas', 'manifest.json'),
      join(root, 'packages', 'ui', 'schemas', 'manifest.json'),
    ]);
  });
});

describe('readCmsSchemaManifest', () => {
  it('reads each schema without its $comment banner', () => {
    const root = makeRoot([{ name: 'ui', schemas: [['Hero', HERO, undefined]] }]); // prettier-ignore
    const [entry] = readCmsSchemaManifest(join(root, 'packages', 'ui', 'schemas', 'manifest.json')); // prettier-ignore

    expect(entry?.typename).toBe('Hero');
    expect(entry?.version).toBe(schemaVersion(HERO));
    expect(entry?.jsonSchema).toEqual(HERO);
  });

  it('refuses a manifest whose version no longer matches the schema file', () => {
    const root = makeRoot([{ name: 'ui', schemas: [['Hero', HERO, 'stale0000000000']] }]); // prettier-ignore

    expect(() => readCmsSchemaManifest(join(root, 'packages', 'ui', 'schemas', 'manifest.json'))).toThrow(CmsSchemaSyncError); // prettier-ignore
  });
});

describe('readCmsSchemaEntries', () => {
  it('refuses a typename generated by two packages', () => {
    const root = makeRoot([
      { name: 'a', schemas: [['Hero', HERO, undefined]] },
      { name: 'b', schemas: [['Hero', HERO, undefined]] },
    ]);

    expect(() => readCmsSchemaEntries(root)).toThrow(/generated twice/);
  });

  it('reads the real repo manifests, each in step with its schema file', () => {
    const entries = readCmsSchemaEntries(process.cwd());
    const typenames = entries.map((entry) => entry.typename);

    expect(typenames).toEqual(expect.arrayContaining(['Card', 'Hero', 'Layout', 'LayoutColumn', 'LayoutGrid'])); // prettier-ignore
  });
});

describe('syncCmsSchemas', () => {
  const entries = [{ jsonSchema: HERO, source: 'Hero.schema.json', typename: 'Hero', version: 'abc' }]; // prettier-ignore

  it('inserts, re-activates and disables inside one locked transaction', async () => {
    const { client, queries } = makeClient((text) => {
      if (text.includes('INSERT INTO schemas')) {
        return [{ typename: 'Hero', version: 'abc' }];
      }

      if (text.includes("SET status = 'DISABLED'")) {
        return [{ typename: 'Hero', version: '1.0.0' }];
      }

      return [];
    });

    const result = await syncCmsSchemas(client, entries);

    expect(result).toEqual({ activated: [], disabled: ['Hero@1.0.0'], inserted: ['Hero@abc'] }); // prettier-ignore
    expect(
      queries.map((query) =>
        query.text.trim().split(/\s+/).slice(0, 3).join(' '),
      ),
    ).toEqual([
      // prettier-ignore
      'BEGIN',
      'SELECT pg_advisory_xact_lock(hashtext($1))',
      'WITH entries AS',
      'WITH entries AS',
      'WITH entries AS',
      'COMMIT',
    ]);
    expect(JSON.parse(String(queries[2]?.values?.[0]))).toEqual([{ json_schema: HERO, typename: 'Hero', version: 'abc' }]); // prettier-ignore
  });

  it('only touches rows that are not already in the target state', async () => {
    const { client, queries } = makeClient(() => {
      return [];
    });

    await syncCmsSchemas(client, entries);
    const writes = queries.map((query) => query.text).filter((text) => text.includes('UPDATE')); // prettier-ignore

    expect(writes[0]).toContain("s.status IS DISTINCT FROM 'ACTIVE'");
    expect(writes[1]).toContain("s.status = 'ACTIVE'");
  });

  it('rolls back and rethrows when a statement fails', async () => {
    const { client, queries } = makeClient((text) => {
      return text.includes('INSERT') ? new Error('boom') : [];
    });

    await expect(syncCmsSchemas(client, entries)).rejects.toThrow('boom');
    expect(queries.at(-1)?.text).toBe('ROLLBACK');
  });
});

describe('describeCmsSchemaSync', () => {
  it('says nothing changed on a no-op run', () => {
    expect(describeCmsSchemaSync(14, { activated: [], disabled: [], inserted: [] })).toMatch(/nothing to change/); // prettier-ignore
  });

  it('lists each kind of change', () => {
    const line = describeCmsSchemaSync(2, { activated: [], disabled: ['Hero@1'], inserted: ['Hero@2'] }); // prettier-ignore

    expect(line).toContain('inserted 1 (Hero@2)');
    expect(line).toContain('disabled 1 (Hero@1)');
    expect(line).not.toContain('re-activated');
  });
});
